def font(run, size=12, bold=False, color=None, name="Calibri"):
    run.font.name = name
    run._element.rPr.rFonts.set(qn("w:eastAsia"), name)
    run.font.size = Pt(size)
    run.bold = bold
    if color:
        run.font.color.rgb = color


def rtl(p):
    pPr = p._p.get_or_add_pPr()
    from docx.oxml import OxmlElement
    bidi = OxmlElement("w:bidi")
    pPr.append(bidi)
    p.alignment = WD_ALIGN_PARAGRAPH.RIGHT


def h(doc, text, level=1):
    p = doc.add_paragraph()
    rtl(p)
    sizes = {1: 16, 2: 14, 3: 12}
    run = p.add_run(text)
    font(run, size=sizes[level], bold=True, color=RGBColor(0x1A, 0x2B, 0x68))
    p.paragraph_format.space_before = Pt(12)
    p.paragraph_format.space_after = Pt(6)


def p_ar(doc, text, bold=False, size=12, space=6):
    p = doc.add_paragraph()
    rtl(p)
    p.paragraph_format.space_after = Pt(space)
    p.paragraph_format.line_spacing_rule = WD_LINE_SPACING.ONE_POINT_FIVE
    run = p.add_run(text)
    font(run, size=size, bold=bold)
    return p


def qa(doc, q, a):
    p_ar(doc, f"س: {q}", bold=True, size=12, space=3)
    p_ar(doc, f"ج: {a}", bold=False, size=12, space=10)


